#include "PwmPin.h"

void PwmPin::begin(uint8_t p)
{
    pin = p;
    brightness = 0;

    pinMode(pin, OUTPUT);

    outReg = portOutputRegister(digitalPinToPort(pin));
    mask = digitalPinToBitMask(pin);

    *outReg &= ~mask;
}

void PwmPin::set(PWM_INT value)
{
    brightness = value;
}

PWM_INT PwmPin::get() const
{
    return brightness;
}


